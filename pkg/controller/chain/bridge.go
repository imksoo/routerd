const routerdGeneratedNetworkdHeader = "# Generated by routerd. Do not edit by hand."

// BridgeController owns the native Linux bridge and port associations. Its
// journal survives failures and removal; networkd artifacts preserve these
// effects without creating another link or address owner.
type BridgeController struct {
	Router           *api.Router
	Store            Store
	DryRun           bool
	NetworkdDir      string
	OperatingSystem  platform.OS
	NativeScope      func(context.Context) (string, error)
	Command          func(context.Context, string, ...string) error
	ReadFile         func(string) ([]byte, error)
	Readlink         func(string) (string, error)
	Interfaces       func() ([]net.Interface, error)
	SetAliasByIndex  func(int, string, string) error
	SetAdminByIndex  func(int, string, bool) error
	DeleteByIndex    func(int, string) error
	SetMasterByIndex func(bridgePort, int, string) error
}

func (c BridgeController) Reconcile(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if c.Router == nil || c.Store == nil {
		return nil
	}
	if c.currentOS() != platform.OSLinux {
		return nil
	}
	return c.reconcileOwnedBridges(ctx)
}

func (c BridgeController) currentOS() platform.OS {
	if c.OperatingSystem != "" {
		return c.OperatingSystem
	}
	return platform.CurrentOS()
}

func (c BridgeController) savePlannedBridgeStatus(resource api.Resource) error {
	previous, err := c.Store.ReadObjectStatus(api.NetAPIVersion, "Bridge", resource.Metadata.Name)
	if err != nil {
		return err
	}
	spec, err := resource.BridgeSpec()
	if err != nil {
		return err
	}
	status := map[string]any{"phase": "Planned", "reason": "DryRun", "ifname": firstNonEmpty(spec.IfName, resource.Metadata.Name)}
	if generation, ok := previous["networkdGeneration"].(string); ok {
		status["networkdGeneration"] = generation
	}
	return c.Store.SaveObjectStatus(api.NetAPIVersion, "Bridge", resource.Metadata.Name, status)
}

func (c BridgeController) saveAppliedBridgeStatus(ctx context.Context, owner bridgeOwner) error {
	if err := c.checkBridgeScope(ctx, owner); err != nil {
		return err
	}
	iface, err := c.observedOwnedBridge(owner)
	if err != nil {
		return err
	}
	if iface == nil {
		return os.ErrNotExist
	}
	healthy, err := c.bridgeHealthy(owner, *iface)
	if err != nil {
		return err
	}
	if !healthy {
		return errors.New("Bridge changed before applied publication")
	}
	if err := c.checkBridgeScope(ctx, owner); err != nil {
		return err
	}
	return c.Store.SaveObjectStatus(api.NetAPIVersion, "Bridge", owner.Resource, map[string]any{"phase": "Healthy", "ifname": iface.Name, "index": iface.Index, "mtu": iface.MTU, "flags": iface.Flags.String(), "members": append([]string(nil), owner.Plan.Members...), "persistent": true, "backend": "routerd/networkd", "networkdGeneration": owner.Plan.digest()})
}

func (c BridgeController) bridgeScope(ctx context.Context) (string, error) {
	if err := ctx.Err(); err != nil {
		return "", err
	}
	readScope := c.NativeScope
	if readScope == nil {
		readScope = platform.KernelNetworkScope
	}
	scope, err := readScope(ctx)
	if err != nil {
		return "", err
	}
	if scope == "" {
		return "", errors.New("Bridge kernel scope is unavailable")
	}
	return scope, ctx.Err()
}

func (c BridgeController) checkBridgeScope(ctx context.Context, owner bridgeOwner) error {
	scope, err := c.bridgeScope(ctx)
	if err != nil {
		return err
	}
	if owner.Scope == "" || owner.Scope != scope {
		return errors.New("Bridge ownership belongs to a different kernel scope")
	}
	return nil
}

func (c BridgeController) networkdPath(path string) string {
	base := strings.TrimSpace(c.NetworkdDir)
	if base == "" {
		defaults, _ := platform.Current()
		base = defaults.NetworkdDropinDir
	}
	if base == "" {
		base = "/etc/systemd/network"
	}
	rel := strings.TrimPrefix(filepath.Clean(path), filepath.Clean("/etc/systemd/network"))
	return filepath.Join(base, strings.TrimPrefix(rel, string(filepath.Separator)))
}

func bridgeInterfaceAliases(router *api.Router) map[string]string {
	out := map[string]string{}
	if router == nil {
		return out
	}
	for _, resource := range router.Spec.Resources {
		switch resource.Kind {
		case "Interface":
			spec, err := resource.InterfaceSpec()
			if err == nil {
				out[resource.Metadata.Name] = spec.IfName
			}
		case "VXLANTunnel":
			spec, err := resource.VXLANTunnelSpec()
			if err == nil {
				out[resource.Metadata.Name] = firstNonEmpty(spec.IfName, resource.Metadata.Name)
			}
		case "VXLANSegment":
			spec, err := resource.VXLANSegmentSpec()
			if err == nil {
				out[resource.Metadata.Name] = firstNonEmpty(spec.IfName, resource.Metadata.Name)
			}
		case "Bridge":
			spec, err := resource.BridgeSpec()
			if err == nil {
				out[resource.Metadata.Name] = firstNonEmpty(spec.IfName, resource.Metadata.Name)
			}
		case "WireGuardInterface":
			spec, err := resource.WireGuardInterfaceSpec()
			if err == nil {
				out[resource.Metadata.Name] = firstNonEmpty(spec.IfName, resource.Metadata.Name)
			}
		}
	}
	return out
}

func (c BridgeController) command(ctx context.Context, name string, args ...string) error {
	if c.Command != nil {
		return c.Command(ctx, name, args...)
	}
	return runCommandContext(ctx, name, args...)
}

func (c BridgeController) readFile(path string) ([]byte, error) {
	if c.ReadFile != nil {
		return c.ReadFile(path)
	}
	return os.ReadFile(path)
}

func (c BridgeController) readlink(path string) (string, error) {
	if c.Readlink != nil {
		return c.Readlink(path)
	}
	return os.Readlink(path)
}

func (c BridgeController) isKernelBridge(ifname string) bool {
	_, err := c.readFile(filepath.Join("/sys/class/net", ifname, "bridge", "stp_state"))
	return err == nil
}

func boolInt(value bool) int {
	if value {
		return 1
	}
	return 0
}
