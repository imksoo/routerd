package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// The stopped keepalived instance's generated configuration retains the exact
// parent/interface/MAC declarations until all corresponding links are removed.
// Parse only our generated hook grammar; never execute configuration text.
func removeConfiguredVMACs(path string, hooks runHooks) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !strings.HasPrefix(string(data), "# Generated by routerd. Do not edit by hand.\n") {
		return fmt.Errorf("keepalived config %s is not owned by routerd", path)
	}
	var entries []vmac
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "notify_master ") {
			continue
		}
		text := strings.TrimSpace(strings.TrimPrefix(line, "notify_master "))
		if len(text) < 2 || text[0] != '"' || text[len(text)-1] != '"' {
			return fmt.Errorf("invalid generated keepalived notify_master")
		}
		fields := strings.Fields(text[1 : len(text)-1])
		if len(fields) < 2 || filepath.Base(fields[0]) != "routerd-vrrp-vmac" || fields[1] != "activate" {
			return fmt.Errorf("unrecognized generated keepalived notify_master")
		}
		opts, err := parseOptions(fields[1:])
		if err != nil {
			return err
		}
		entries = append(entries, opts.vmacs...)
	}
	for _, entry := range entries {
		if hooks.inspectVMAC == nil {
			return fmt.Errorf("VMAC removal ownership inspection unavailable")
		}
		// Production inspection verifies private macvlan type, parent and mode.
		state, err := hooks.inspectVMAC(entry)
		if err != nil {
			return err
		}
		if !state.exists {
			continue
		}
		if !state.macMatches {
			return fmt.Errorf("refuse to remove VMAC %s: MAC differs from owned keepalived configuration", entry.ifname)
		}
		if hooks.command == nil {
			return fmt.Errorf("VMAC removal command unavailable")
		}
		out, err := hooks.command("ip", "link", "delete", "dev", entry.ifname)
		if err != nil {
			return fmt.Errorf("remove VMAC %s: %w: %s", entry.ifname, err, strings.TrimSpace(string(out)))
		}
	}
	return nil
}
