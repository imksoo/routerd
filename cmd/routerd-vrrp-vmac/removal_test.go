func TestRemoveConfiguredVMACsUsesValidatedIdentityAndRetries(t *testing.T) {
	cfg := filepath.Join(t.TempDir(), "keepalived.conf")
	data := "# Generated by routerd. Do not edit by hand.\nnotify_master \"/usr/sbin/routerd-vrrp-vmac activate --vmac wan,wan-vmac,02:00:5e:00:01:01,,false --vmac lan,lan-vmac,02:00:5e:00:01:02,fe80::2,true\"\n"
	if err := os.WriteFile(cfg, []byte(data), 0600); err != nil {
		t.Fatal(err)
	}
	present := map[string]bool{"wan-vmac": true, "lan-vmac": true}
	fail := true
	hooks := runHooks{inspectVMAC: func(v vmac) (vmacRuntimeState, error) {
		return vmacRuntimeState{exists: present[v.ifname], macMatches: true}, nil
	}, command: func(name string, args ...string) ([]byte, error) {
		if name != "ip" || strings.Join(args[:3], " ") != "link delete dev" {
			t.Fatalf("unexpected command %s %v", name, args)
		}
		iface := args[3]
		if iface == "lan-vmac" && fail {
			return nil, errors.New("delete failed")
		}
		delete(present, iface)
		return nil, nil
	}}
	if err := runWithHooks([]string{"remove-config", cfg}, hooks); err == nil {
		t.Fatal("partial removal failure hidden")
	}
	if present["wan-vmac"] || !present["lan-vmac"] {
		t.Fatalf("unexpected first removal: %v", present)
	}
	fail = false
	if err := runWithHooks([]string{"remove-config", cfg}, hooks); err != nil {
		t.Fatal(err)
	}
	if len(present) != 0 {
		t.Fatalf("links retained: %v", present)
	}
}

func TestRemoveConfiguredVMACsRefusesForeignIdentityOrConfiguration(t *testing.T) {
	for _, scenario := range []string{"header", "hook", "parent", "mac"} {
		t.Run(scenario, func(t *testing.T) {
			cfg := filepath.Join(t.TempDir(), "keepalived.conf")
			data := "# Generated by routerd. Do not edit by hand.\nnotify_master \"/usr/sbin/routerd-vrrp-vmac activate --parent wan --interface wan-vmac --mac 02:00:5e:00:01:01\"\n"
			if scenario == "header" {
				data = strings.Replace(data, "Generated by routerd", "locally managed", 1)
			}
			if scenario == "hook" {
				data = strings.Replace(data, "/usr/sbin/routerd-vrrp-vmac", "/bin/sh", 1)
			}
			if err := os.WriteFile(cfg, []byte(data), 0600); err != nil {
				t.Fatal(err)
			}
			hooks := runHooks{inspectVMAC: func(vmac) (vmacRuntimeState, error) {
				if scenario == "parent" {
					return vmacRuntimeState{}, errors.New("foreign native parent")
				}
				return vmacRuntimeState{exists: true, macMatches: scenario != "mac"}, nil
			}, command: func(string, ...string) ([]byte, error) { t.Fatal("foreign link authorized deletion"); return nil, nil }}
			if err := runWithHooks([]string{"remove-config", cfg}, hooks); err == nil {
				t.Fatal("foreign configuration or identity accepted")
			}
		})
	}
}

func TestRemoveConfiguredVMACsWithdrawsDeferredVIPBeforeLinks(t *testing.T) {
	cfg := filepath.Join(t.TempDir(), "keepalived.conf")
	data := "# Generated by routerd. Do not edit by hand.\nnotify_master \"/usr/sbin/routerd-vrrp-vmac activate --parent lan --interface lan-vmac --mac 02:00:5e:00:01:02 --resource gateway --deferred-address 198.18.30.1/32 --deferred-interface lan\"\n"
	if err := os.WriteFile(cfg, []byte(data), 0600); err != nil {
		t.Fatal(err)
	}
	for _, scenario := range []string{"present", "links already absent", "foreign", "withdraw failure"} {
		t.Run(scenario, func(t *testing.T) {
			withdrawn := false
			deleted := false
			hooks := runHooks{
				inspectVMAC: func(vmac) (vmacRuntimeState, error) {
					return vmacRuntimeState{exists: scenario != "links already absent", macMatches: scenario != "foreign"}, nil
				},
				withdrawDeferredVIP: func(opts options) error {
					if scenario == "foreign" {
						t.Fatal("foreign link authorized VIP withdrawal")
					}
					if opts.deferredAddress != "198.18.30.1/32" || opts.deferredInterface != "lan" {
						t.Fatalf("wrong VIP %+v", opts)
					}
					if scenario == "withdraw failure" {
						return errors.New("withdraw failed")
					}
					withdrawn = true
					return nil
				},
				command: func(string, ...string) ([]byte, error) {
					if !withdrawn {
						t.Fatal("link removed before VIP withdrawal")
					}
					deleted = true
					return nil, nil
				},
			}
			err := runWithHooks([]string{"remove-config", cfg}, hooks)
			wantError := scenario == "foreign" || scenario == "withdraw failure"
			if (err != nil) != wantError {
				t.Fatalf("error=%v wantError=%t", err, wantError)
			}
			if wantError && deleted {
				t.Fatal("link deleted after failed ownership check or withdrawal")
			}
			if !wantError && !withdrawn {
				t.Fatal("deferred VIP retained")
			}
		})
	}
}
