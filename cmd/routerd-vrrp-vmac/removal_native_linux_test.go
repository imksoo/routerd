//go:build linux

package main

import (
	"fmt"
	"net"
	"os"
	"path/filepath"
	"testing"

	"github.com/vishvananda/netlink"
)

func TestRemoveConfiguredVMACsNativeLinux(t *testing.T) {
	if os.Getenv("ROUTERD_RUN_NETNS") != "1" {
		t.Skip("requires explicit isolated network namespace")
	}
	current, err := os.Readlink("/proc/self/ns/net")
	if err != nil {
		t.Fatal(err)
	}
	initial, err := os.Readlink("/proc/1/ns/net")
	if err != nil {
		t.Fatal(err)
	}
	if current == initial {
		t.Fatal("refuse native mutations without a separate network namespace")
	}
	parent := &netlink.Dummy{LinkAttrs: netlink.LinkAttrs{Name: "rd15-vp"}}
	if err := netlink.LinkAdd(parent); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { netlink.LinkDel(parent) })
	vip, err := netlink.ParseAddr("198.18.30.1/32")
	if err != nil {
		t.Fatal(err)
	}
	if err := netlink.AddrAdd(parent, vip); err != nil {
		t.Fatal(err)
	}
	cfg := filepath.Join(t.TempDir(), "keepalived.conf")
	data := fmt.Sprintf("# Generated by routerd. Do not edit by hand.\nnotify_master \"/usr/sbin/routerd-vrrp-vmac activate --parent %s --interface rd15-vm --mac 02:00:5e:00:01:01 --resource gateway --deferred-address 198.18.30.1/32 --deferred-interface %s\"\n", parent.Name, parent.Name)
	if err := os.WriteFile(cfg, []byte(data), 0600); err != nil {
		t.Fatal(err)
	}
	foreign := &netlink.Dummy{LinkAttrs: netlink.LinkAttrs{Name: "rd15-vm"}}
	if err := netlink.LinkAdd(foreign); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"remove-config", cfg}); err == nil {
		t.Fatal("foreign native type accepted")
	}
	if _, err := netlink.LinkByName("rd15-vm"); err != nil {
		t.Fatalf("foreign link deleted: %v", err)
	}
	if err := netlink.LinkDel(foreign); err != nil {
		t.Fatal(err)
	}
	mac, _ := net.ParseMAC("02:00:5e:00:01:01")
	owned := &netlink.Macvlan{LinkAttrs: netlink.LinkAttrs{Name: "rd15-vm", ParentIndex: parent.Index, HardwareAddr: mac}, Mode: netlink.MACVLAN_MODE_PRIVATE}
	if err := netlink.LinkAdd(owned); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"remove-config", cfg}); err != nil {
		t.Fatal(err)
	}
	if _, err := netlink.LinkByName("rd15-vm"); err == nil {
		t.Fatal("owned VMAC retained")
	}
	if _, err := netlink.LinkByName(parent.Name); err != nil {
		t.Fatalf("physical parent removed: %v", err)
	}
	addresses, err := netlink.AddrList(parent, netlink.FAMILY_V4)
	if err != nil {
		t.Fatal(err)
	}
	if len(addresses) != 0 {
		t.Fatalf("deferred VIP retained after VMAC removal: %v", addresses)
	}
	if err := run([]string{"remove-config", cfg}); err != nil {
		t.Fatalf("absent VMAC retry failed: %v", err)
	}
}
