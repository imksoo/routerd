// specgen generates the closed resource-spec contract and ordinary field copies.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"
)

var fset = token.NewFileSet()
var types = map[string]ast.Expr{}
var used = map[string]bool{}
var output bytes.Buffer

func spelling(e ast.Expr) string { var b bytes.Buffer; printer.Fprint(&b, fset, e); return b.String() }
func main() {
	files, err := parser.ParseDir(fset, "pkg/api", func(i os.FileInfo) bool {
		return i.Name() != "spec_generated.go" && !strings.HasSuffix(i.Name(), "_test.go")
	}, 0)
	if err != nil {
		panic(err)
	}
	for _, f := range files["api"].Files {
		for _, d := range f.Decls {
			if g, ok := d.(*ast.GenDecl); ok {
				for _, s := range g.Specs {
					if t, ok := s.(*ast.TypeSpec); ok {
						types[t.Name.Name] = t.Type
					}
				}
			}
		}
	}
	kinds, err := parser.ParseFile(fset, "pkg/api/resource_kinds.go", nil, 0)
	if err != nil {
		panic(err)
	}
	var names, kindNames []string
	used["ApplyPolicySpec"] = true
	ast.Inspect(kinds, func(n ast.Node) bool {
		lit, ok := n.(*ast.CompositeLit)
		if !ok || len(lit.Elts) != 3 {
			return true
		}
		k, ok := lit.Elts[1].(*ast.BasicLit)
		if !ok {
			return true
		}
		s, ok := lit.Elts[2].(*ast.CompositeLit)
		if !ok {
			return true
		}
		id, ok := s.Type.(*ast.Ident)
		if !ok {
			return true
		}
		name, err := strconv.Unquote(k.Value)
		if err != nil {
			panic(err)
		}
		names = append(names, id.Name)
		kindNames = append(kindNames, name)
		return true
	})
	fmt.Fprintln(&output, "// Code generated by go run ./internal/cmd/specgen; DO NOT EDIT.\n// SPDX-License-Identifier: BSD-3-Clause\n\npackage api")
	fmt.Fprintln(&output, "import \"fmt\"\n\nfunc decodeResourceSpec(kind string, decode func(ResourceSpec) error) (ResourceSpec,error) { switch kind {")
	for i, n := range names {
		fmt.Fprintf(&output, "case %q: var spec %s; if err:=decode(&spec);err!=nil{return nil,err}; return spec,nil\n", kindNames[i], n)
	}
	output.WriteString("}; return nil,fmt.Errorf(\"unsupported resource kind %s\",kind) }\n")
	for _, n := range names {
		fmt.Fprintf(&output, "func (s %s) cloneSpec() ResourceSpec { return clone%s(s) }\n", n, n)
		used[n] = true
	}
	for {
		pending := []string{}
		for n, done := range used {
			if done {
				pending = append(pending, n)
			}
		}
		if len(pending) == 0 {
			break
		}
		sort.Strings(pending)
		for _, n := range pending {
			used[n] = false
			generate(n)
		}
	}
	data, err := format.Source(output.Bytes())
	if err != nil {
		os.Stderr.Write(output.Bytes())
		panic(err)
	}
	if len(os.Args) > 1 && os.Args[1] == "-check" {
		current, err := os.ReadFile("pkg/api/spec_generated.go")
		if err != nil {
			panic(err)
		}
		if !bytes.Equal(current, data) {
			fmt.Fprintln(os.Stderr, "resource spec code is stale; run make generate-spec")
			os.Exit(1)
		}
		return
	}
	if err = os.WriteFile("pkg/api/spec_generated.go", data, 0644); err != nil {
		panic(err)
	}
}
func generate(n string) {
	fmt.Fprintf(&output, "func clone%s(s %s) %s { out := s\n", n, n, n)
	if s, ok := types[n].(*ast.StructType); ok {
		for _, f := range s.Fields.List {
			names := f.Names
			if len(names) == 0 {
				switch t := f.Type.(type) {
				case *ast.Ident:
					names = []*ast.Ident{t}
				default:
					panic("unsupported embedded type")
				}
			}
			for _, name := range names {
				copyField("out."+name.Name, "s."+name.Name, f.Type)
			}
		}
	} else {
		panic("nonstruct " + n)
	}
	fmt.Fprintln(&output, "return out }")
}
func needs(e ast.Expr) bool {
	switch t := e.(type) {
	case *ast.Ident:
		if v, ok := types[t.Name]; ok {
			return needs(v)
		}
		return false
	case *ast.StarExpr, *ast.MapType:
		return true
	case *ast.ArrayType:
		return t.Len == nil || needs(t.Elt)
	case *ast.StructType:
		for _, f := range t.Fields.List {
			if needs(f.Type) {
				return true
			}
		}
		return false
	case *ast.SelectorExpr:
		return false
	default:
		panic("unsupported clone type " + spelling(e))
	}
}
func copyField(dst, src string, e ast.Expr) {
	if dst == src && needs(e) {
		fmt.Fprintf(&output, "{ original := %s\n", src)
		copyField(dst, "original", e)
		fmt.Fprintln(&output, "}")
		return
	}
	if !needs(e) {
		return
	}
	switch t := e.(type) {
	case *ast.Ident:
		if _, exists := used[t.Name]; !exists {
			used[t.Name] = true
		}
		fmt.Fprintf(&output, "%s = clone%s(%s)\n", dst, t.Name, src)
	case *ast.StarExpr:
		fmt.Fprintf(&output, "if %s != nil { value := *%s\n", src, src)
		copyField("value", "(*"+src+")", t.X)
		fmt.Fprintf(&output, "%s = &value }\n", dst)
	case *ast.ArrayType:
		if t.Len != nil {
			fmt.Fprintf(&output, "for i := range %s {\n", src)
			copyField(dst+"[i]", src+"[i]", t.Elt)
			fmt.Fprintln(&output, "}")
			return
		}
		fmt.Fprintf(&output, "if %s != nil { %s = make(%s, len(%s)); copy(%s,%s)\n", src, dst, spelling(e), src, dst, src)
		if needs(t.Elt) {
			fmt.Fprintf(&output, "for i := range %s {\n", src)
			copyField(dst+"[i]", src+"[i]", t.Elt)
			fmt.Fprintln(&output, "}")
		}
		fmt.Fprintln(&output, "}")
	case *ast.MapType:
		fmt.Fprintf(&output, "if %s != nil { %s = make(%s,len(%s)); for key, value := range %s {\n", src, dst, spelling(e), src, src)
		copyField("value", "value", t.Value)
		fmt.Fprintf(&output, "%s[key] = value } }\n", dst)
	default:
		panic("unsupported clone field " + spelling(e))
	}
}
